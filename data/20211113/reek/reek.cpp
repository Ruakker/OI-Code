const int base[6] = {1, 1, 4, 5, 1, 4};
std::string ans;

std::string getMost(long long n) {
    std::string res;
    n >>= 4;
    for (int i = 4; n; n >>= 1, ++i)
        if (n & 1) res.append(pow2[i] + '+');
    return res;
}

